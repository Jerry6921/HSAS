"""Generate the TypeScript contract surface consumed by the UI.

Usage: .venv/bin/python scripts/generate_ui_contracts.py
"""

from __future__ import annotations

from pathlib import Path

from hsas.application.material_search import MaterialSearchResult
from hsas.codegen.typescript import models_to_typescript
from hsas.domain.information.attention import AttentionSnapshot


def render_ui_contracts() -> str:
    """Return the full contract module; the only emitter is hsas.codegen."""
    return models_to_typescript(
        {
            "AttentionSnapshot": AttentionSnapshot,
            "MaterialSearchResult": MaterialSearchResult,
        },
        "// Generated by scripts/generate_ui_contracts.py; do not edit manually.",
    )


def main() -> None:
    target = Path(__file__).parents[1] / "ui/src/contracts.ts"
    target.write_text(render_ui_contracts(), encoding="utf-8")


if __name__ == "__main__":
    main()
