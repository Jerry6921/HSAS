"""Stable use-case port shared by the MCP and UI modules."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol, runtime_checkable


class HIQSPortError(RuntimeError):
    """Safe error that delivery adapters may return to a user or agent."""


@runtime_checkable
class AppleDeliveryPort(Protocol):
    def apple_status(self) -> dict[str, Any]: ...
    def apple_configure(self, payload: dict[str, Any]) -> dict[str, Any]: ...
    def apple_projection(self) -> dict[str, Any]: ...
    def apple_check(self) -> dict[str, Any]: ...
    def apple_sync(self) -> dict[str, Any]: ...
    def apple_worker(self, payload: dict[str, Any]) -> dict[str, Any]: ...


@runtime_checkable
class NotionDeliveryPort(Protocol):
    """Deliver canonical facts to Notion while preserving personal state."""

    def notion_projection(self) -> dict[str, Any]: ...

    def notion_export(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def notion_status(self) -> dict[str, Any]: ...

    def notion_configure(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def notion_check(self) -> dict[str, Any]: ...

    def notion_sync(self) -> dict[str, Any]: ...

    def notion_worker(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def notion_controls(self) -> dict[str, Any]: ...

    def notion_controls_tick(self, payload: dict[str, Any] | None = None) -> dict[str, Any]: ...


@runtime_checkable
class InformationQueryPort(Protocol):
    """Read validated information, materials, evidence and calendar projections."""

    @property
    def resources_dir(self) -> Path: ...

    def information_snapshot(self) -> dict[str, Any]: ...

    def status_snapshot(self) -> dict[str, Any]: ...

    def attention_snapshot(self, horizon_days: int = 14) -> dict[str, Any]: ...

    def calendar_ics(self) -> bytes: ...

    def materials_manifest(self, course_ids: list[str] | None = None) -> dict[str, Any]: ...

    def search_materials(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def get_evidence(self, evidence_id: str) -> dict[str, Any]: ...

    def get_evidence_content(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def explain_evidence(self, evidence_id: str) -> dict[str, Any]: ...

    def query_course(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def material_file(self, relative_path: str) -> tuple[Path, str]: ...

    def source_preview(
        self,
        relative_path: str,
        page_numbers: list[int] | None = None,
    ) -> dict[str, Any]: ...

    def moodle_page_preview(self, payload: dict[str, Any]) -> dict[str, Any]: ...


@runtime_checkable
class InformationCommandPort(Protocol):
    """Validate and apply explicitly confirmed canonical information changes."""

    def information_update_schema(self) -> dict[str, Any]: ...

    def validate_information_update(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def apply_information_update(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def save_recent_update_summary(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def add_course(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def delete_course(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def delete_courses(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def add_calendar_event(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def delete_calendar_event(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def process_ocr_queue(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def apply_personal_inbox(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def personal_inbox_snapshot(self) -> dict[str, Any]: ...

    def add_personal_inbox(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def add_attention_draft(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def personal_inbox_entry(self, entry_id: str) -> dict[str, Any]: ...

    def pending_changes(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def acknowledge_changes(self, payload: dict[str, Any]) -> dict[str, Any]: ...


@runtime_checkable
class CourseSyncPort(Protocol):
    """Authenticate and synchronize authorized HKU course sources."""

    def verify_moodle_session(self) -> dict[str, Any]: ...

    def login_moodle(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def synchronize_courses(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def start_course_sync(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def retry_failed_course_sync(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def course_sync_status(self) -> dict[str, Any]: ...

    def cancel_course_sync(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def hydrate_course_materials(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def login_class_planner(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def synchronize_class_planner(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def login_sis_course_info(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def synchronize_sis_course_info(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def synchronize_sis_enrollment(self, payload: dict[str, Any]) -> dict[str, Any]: ...


@runtime_checkable
class ApplicationLifecyclePort(Protocol):
    """Expose the pinned, local-application update lifecycle."""

    def application_update_status(self) -> dict[str, object]: ...

    def apply_application_update(self, payload: dict[str, Any]) -> dict[str, object]: ...


@runtime_checkable
class CourseNotesPort(Protocol):
    """Checkpoint Agent-authored study artifacts outside canonical facts."""

    def create_course_notes(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def course_notes_schema(self) -> dict[str, Any]: ...

    def course_notes(self, run_id: str | None = None, artifact_id: str | None = None) -> dict[str, Any]: ...

    def read_course_note_source(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def save_course_notes(self, payload: dict[str, Any]) -> dict[str, Any]: ...


@runtime_checkable
class CoursePlanningPort(Protocol):
    """Plan approved course pools and checkpoint Agent-operated enrolment."""

    def course_planning_schema(self) -> dict[str, Any]: ...

    def create_course_plan(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def course_plan(self, run_id: str | None = None, observation_sha256: str | None = None) -> dict[str, Any]: ...

    def authorize_course_plan(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def reconcile_course_plan(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def next_course_plan_action(self, payload: dict[str, Any]) -> dict[str, Any]: ...

    def cancel_course_plan(self, payload: dict[str, Any]) -> dict[str, Any]: ...


@runtime_checkable
class HIQSPort(
    AppleDeliveryPort,
    CoursePlanningPort,
    CourseNotesPort,
    NotionDeliveryPort,
    InformationQueryPort,
    InformationCommandPort,
    CourseSyncPort,
    ApplicationLifecyclePort,
    Protocol,
):
    """Aggregate stable capabilities for delivery adapters and composition."""
