"""Verify checked-in generated Agent/UI contracts match the current models."""

from __future__ import annotations

from difflib import unified_diff
from pathlib import Path
import sys

from hsas.application.material_search import MaterialSearchResult
from hsas.codegen import schema_to_typescript
from hsas.domain.information import InformationUpdate
from hsas.domain.information.attention import AttentionSnapshot

try:
    from scripts.generate_ui_contracts import render_model
except ModuleNotFoundError:  # direct ``python scripts/check_generated.py`` execution
    from generate_ui_contracts import render_model


ROOT = Path(__file__).parents[1]


def render_ui_contracts() -> str:
    schemas: list[tuple[str, dict[str, object]]] = []
    for name, model in (("AttentionSnapshot", AttentionSnapshot), ("MaterialSearchResult", MaterialSearchResult)):
        root = model.model_json_schema()
        schemas.append((name, root))
        schemas.extend(root.get("$defs", {}).items())
    output = ["// Generated by scripts/generate_ui_contracts.py; do not edit manually.", ""]
    output.extend(render_model(name, schema) for name, schema in schemas)
    return "\n\n".join(output) + "\n"


def _check(path: Path, expected: str) -> bool:
    actual = path.read_text(encoding="utf-8") if path.exists() else ""
    if actual == expected:
        return True
    print(f"Generated file is stale: {path}", file=sys.stderr)
    diff = unified_diff(
        actual.splitlines(),
        expected.splitlines(),
        fromfile=str(path),
        tofile=f"{path} (generated)",
        lineterm="",
    )
    print("\n".join(list(diff)[:80]), file=sys.stderr)
    return False


def main() -> int:
    checks = {
        ROOT / "ui/src/contracts.ts": render_ui_contracts(),
        ROOT / "ui/src/generated/information-schema.ts": schema_to_typescript(
            InformationUpdate.model_json_schema()
        ),
    }
    results = [_check(path, expected) for path, expected in checks.items()]
    return 0 if all(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
