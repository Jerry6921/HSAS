"""Small dependency-free JSON Schema to TypeScript generator.

The output is deliberately boring and deterministic so generated contracts can be
checked into the UI without adding a runtime dependency. Every UI contract must
come from here: a second hand-written emitter is how the checked-in types drifted
away from the backend models.
"""

from __future__ import annotations

import json
from typing import Any


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _render_type(value: dict[str, Any], *, name: str | None = None) -> str:
    if "$ref" in value:
        return value["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in value:
        options = [_render_type(option) for option in value["anyOf"]]
        return " | ".join(dict.fromkeys(options))
    if "oneOf" in value:
        options = [_render_type(option) for option in value["oneOf"]]
        return " | ".join(dict.fromkeys(options))
    if "allOf" in value:
        options = [_render_type(option) for option in value["allOf"]]
        return " & ".join(dict.fromkeys(options))
    if "enum" in value:
        return " | ".join(_literal(item) for item in value["enum"])
    if "const" in value:
        return _literal(value["const"])
    kind = value.get("type")
    if kind == "array":
        return f"Array<{_render_type(value.get('items', {}))}>"
    if kind == "null":
        return "null"
    if kind == "object" or "properties" in value:
        additional = value.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {_render_type(additional)}>"
        if additional is True or (additional is None and "properties" not in value):
            return "Record<string, unknown>"
        return name or "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
    }.get(kind, "unknown")


def _emit_interface(lines: list[str], name: str, schema: dict[str, Any]) -> None:
    properties = schema.get("properties", {})
    if not properties:
        lines.append(f"export type {name} = {_render_type(schema, name=name)};")
        lines.append("")
        return
    required = set(schema.get("required", []))
    nested: list[tuple[str, dict[str, Any]]] = []
    lines.append(f"export interface {name} {{")
    for key, child in properties.items():
        if (
            isinstance(child, dict)
            and "properties" in child
            and "additionalProperties" not in child
            and "$ref" not in child
        ):
            child_name = f"{name}_{key}"
            optional = "" if key in required else "?"
            lines.append(
                f"  {json.dumps(key, ensure_ascii=False)}{optional}: {child_name};"
            )
            nested.append((child_name, child))
        else:
            optional = "" if key in required else "?"
            lines.append(
                f"  {json.dumps(key, ensure_ascii=False)}{optional}: {_render_type(child)};"
            )
    lines.append("}")
    lines.append("")
    for child_name, child_schema in nested:
        _emit_interface(lines, child_name, child_schema)


def schema_to_typescript(schema: dict[str, Any], root_name: str = "InformationUpdate") -> str:
    """Render one model schema as TypeScript interfaces."""
    lines = ["// Generated by `hsas information types`; do not edit manually.", ""]
    for name, definition in schema.get("$defs", {}).items():
        if definition.get("type") == "object" or "properties" in definition:
            _emit_interface(lines, name, definition)
    if schema.get("type") == "object" or "properties" in schema:
        _emit_interface(lines, root_name, schema)
    return "\n".join(lines).rstrip() + "\n"


def models_to_typescript(models: dict[str, Any], header: str) -> str:
    """Render several pydantic models into one deterministic contract module."""
    lines = [header, ""]
    emitted: set[str] = set()
    ordered: list[tuple[str, dict[str, Any]]] = []
    for name, model in models.items():
        root = model.model_json_schema()
        for definition_name, definition in root.get("$defs", {}).items():
            if definition_name in emitted:
                continue
            emitted.add(definition_name)
            ordered.append((definition_name, definition))
        if name in emitted:
            continue
        emitted.add(name)
        ordered.append((name, root))
    for name, schema in ordered:
        if schema.get("type") == "object" or "properties" in schema:
            _emit_interface(lines, name, schema)
    return "\n".join(lines).rstrip() + "\n"
